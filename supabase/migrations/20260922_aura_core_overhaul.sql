-- Weekly settlement. Intended to be invoked by the authenticated server cron route.
create or replace function public.settle_weekly_pool()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_end timestamptz := date_trunc('day', now()) - (extract(dow from now())::int * interval '1 day');
  v_start timestamptz := v_end - interval '7 days';
  v_existing bigint;
  v_post_id bigint;
  v_user_id uuid;
  v_pool double precision;
begin
  select id into v_existing from public.weekly_rounds
  where starts_at=v_start and ends_at=v_end and settled_at is not null;

  if v_existing is not null then return jsonb_build_object('status','already_settled'); end if;

  select id,user_id into v_post_id,v_user_id
  from public.posts
  where created_at >= v_start and created_at < v_end
  order by aura desc, created_at asc
  limit 1;

  select coalesce(amount,0) into v_pool from public.tax_bucket where id=1 for update;

  insert into public.weekly_rounds(starts_at,ends_at,winner_post_id,winner_user_id,pool_amount,settled_at)
  values(v_start,v_end,v_post_id,v_user_id,v_pool,now())
  on conflict (starts_at,ends_at)
  do update set winner_post_id=excluded.winner_post_id,winner_user_id=excluded.winner_user_id,
    pool_amount=excluded.pool_amount,settled_at=excluded.settled_at;

  if v_user_id is not null and v_pool > 0 then
    perform public._apply_aura_delta(v_user_id,v_pool,'weekly_prize','Weekly top-post prize');
  end if;

  update public.tax_bucket set amount=0, last_reset=current_date where id=1;

  return jsonb_build_object('status','ok','winner_user_id',v_user_id,'winner_post_id',v_post_id,'pool',v_pool);
end;
$$;
revoke all on function public.settle_weekly_pool() from public, anon, authenticated;
grant execute on function public.settle_weekly_pool() to service_role;

-- Repair the existing ledger without rewriting balances: add a reconciliation row only when needed.
with latest as (
  select distinct on (user_id) user_id, balance_after
  from public.aura_ledger
  order by user_id, created_at desc, id desc
)
insert into public.aura_ledger(user_id,amount,type,description,balance_after)
select p.id,
       round((p.aura - coalesce(l.balance_after,0))::numeric,1)::double precision,
       'reconciliation',
       case when l.user_id is null then 'Ledger starting balance after economy migration'
            else 'Ledger reconciliation after economy migration' end,
       p.aura
from public.profiles p
left join latest l on l.user_id=p.id
where l.user_id is null or abs(p.aura - l.balance_after) > 0.0001;
