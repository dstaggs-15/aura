-- Cast a post vote transactionally.
create or replace function public.cast_post_vote(p_post_id bigint, p_value integer)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public._require_aura_member();
  v_owner uuid;
  v_prev integer := 0;
  v_delta integer;
  v_old_cost double precision;
  v_new_cost double precision;
  v_cost_delta double precision;
  v_owner_gain double precision;
  v_big_count integer;
  v_tags uuid[];
  v_tag uuid;
  v_tag_share double precision;
  v_tag_count integer;
  v_post_aura double precision;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;
  if p_value not in (-50,-10,-5,-1,1,5,10,50) then raise exception 'invalid vote'; end if;

  select user_id into v_owner
  from public.posts
  where id = p_post_id
  for update;

  if v_owner is null then raise exception 'post not found'; end if;
  if v_owner = v_uid then raise exception 'cannot vote on your own post'; end if;

  select value into v_prev
  from public.votes
  where voter_id = v_uid and post_id = p_post_id;
  v_prev := coalesce(v_prev, 0);

  if v_prev = p_value then
    return jsonb_build_object('status','unchanged');
  end if;

  -- Max 3 big votes to the same person per rolling 24h. The 4th attempt costs 50 aura.
  if abs(p_value) = 50 and abs(v_prev) <> 50 then
    select count(*) into v_big_count
    from public.vote_events
    where voter_id = v_uid
      and target_user_id = v_owner
      and accepted = true
      and abs(new_value) = 50
      and created_at > now() - interval '24 hours';

    if v_big_count >= 3 then
      perform public._apply_aura_delta(v_uid, -50, 'glazing_penalty', 'Too many big votes to the same person in 24h');
      insert into public.vote_events(voter_id,target_user_id,post_id,old_value,new_value,delta,accepted)
      values (v_uid,v_owner,p_post_id,v_prev,p_value,p_value-v_prev,false);
      return jsonb_build_object('status','glazing_penalty','penalty',50);
    end if;
  end if;

  insert into public.votes(voter_id, post_id, value)
  values (v_uid, p_post_id, p_value)
  on conflict (voter_id, post_id)
  do update set value = excluded.value;

  v_delta := p_value - v_prev;

  update public.posts
  set aura = round((coalesce(aura,0) + v_delta)::numeric, 1)::double precision
  where id = p_post_id
  returning aura into v_post_aura;

  v_old_cost := case when v_prev > 0 then public._aura_vote_cost(v_prev) else 0 end;
  v_new_cost := case when p_value > 0 then public._aura_vote_cost(p_value) else 0 end;
  v_cost_delta := v_new_cost - v_old_cost;

  if v_cost_delta <> 0 then
    perform public._apply_aura_delta(
      v_uid,
      -v_cost_delta,
      case when v_cost_delta > 0 then 'vote_cost' else 'vote_refund' end,
      case when v_cost_delta > 0
        then 'Cost to send +' || p_value || ' vote'
        else 'Vote cost refund'
      end
    );
  end if;

  v_owner_gain := v_delta;
  if v_owner_gain <> 0 then
    perform public._apply_income_with_clown_tax(
      v_owner,
      v_owner_gain,
      'post_vote',
      case when v_delta > 0 then '+' else '' end || v_delta || ' change on your post'
    );
  end if;

  select array_agg(tagged_user_id)
  into v_tags
  from public.post_tags
  where post_id = p_post_id and tagged_user_id <> v_owner;

  v_tag_count := coalesce(array_length(v_tags, 1), 0);
  if v_tag_count > 0 and v_delta <> 0 then
    -- The total tag bonus is capped at 50% and split across all tagged users.
    v_tag_share := round(((v_delta * 0.5) / v_tag_count)::numeric, 1)::double precision;
    foreach v_tag in array v_tags loop
      if v_tag_share <> 0 then
        perform public._apply_income_with_clown_tax(
          v_tag,
          v_tag_share,
          'tag_share',
          'Share from a tagged post vote'
        );
      end if;
    end loop;
  end if;

  insert into public.vote_events(voter_id,target_user_id,post_id,old_value,new_value,delta,accepted)
  values (v_uid,v_owner,p_post_id,v_prev,p_value,v_delta,true);

  return jsonb_build_object(
    'status','ok',
    'post_aura',v_post_aura,
    'delta',v_delta,
    'vote_cost_delta',v_cost_delta
  );
end;
$$;
grant execute on function public.cast_post_vote(bigint,integer) to authenticated;

-- Profile votes are intentionally smaller and use the same atomic ledger.
create or replace function public.cast_profile_vote(p_target_id uuid, p_value integer)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public._require_aura_member();
  v_prev integer := 0;
  v_delta integer;
  v_old_cost double precision;
  v_new_cost double precision;
  v_cost_delta double precision;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;
  if p_target_id = v_uid then raise exception 'cannot vote on yourself'; end if;
  if p_value not in (-10,-5,-1,1,5,10) then raise exception 'invalid profile vote'; end if;

  select value into v_prev
  from public.profile_votes
  where voter_id = v_uid and target_id = p_target_id;
  v_prev := coalesce(v_prev, 0);

  if v_prev = p_value then return jsonb_build_object('status','unchanged'); end if;

  insert into public.profile_votes(voter_id,target_id,value)
  values (v_uid,p_target_id,p_value)
  on conflict (voter_id,target_id)
  do update set value = excluded.value;

  v_delta := p_value - v_prev;
  v_old_cost := case when v_prev > 0 then public._aura_vote_cost(v_prev) else 0 end;
  v_new_cost := case when p_value > 0 then public._aura_vote_cost(p_value) else 0 end;
  v_cost_delta := v_new_cost - v_old_cost;

  if v_cost_delta <> 0 then
    perform public._apply_aura_delta(v_uid,-v_cost_delta,
      case when v_cost_delta > 0 then 'profile_vote_cost' else 'profile_vote_refund' end,
      'Profile vote cost adjustment');
  end if;

  perform public._apply_income_with_clown_tax(
    p_target_id,
    v_delta,
    'profile_vote',
    'Profile vote changed by ' || v_delta
  );

  return jsonb_build_object('status','ok','delta',v_delta,'vote_cost_delta',v_cost_delta);
end;
$$;
grant execute on function public.cast_profile_vote(uuid,integer) to authenticated;

create or replace function public.daily_checkin()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public._require_aura_member();
  v_last date;
  v_streak integer;
  v_new_streak integer;
  v_balance double precision;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;

  select last_checkin, streak into v_last, v_streak
  from public.profiles
  where id = v_uid
  for update;

  if v_last = current_date then
    return jsonb_build_object('status','already');
  end if;

  v_new_streak := case when v_last = current_date - 1 then coalesce(v_streak,0) + 1 else 1 end;
  v_balance := public._apply_aura_delta(v_uid,5,'checkin','Day ' || v_new_streak || ' check-in');

  update public.profiles
  set streak = v_new_streak,
      last_checkin = current_date,
      last_inactivity_penalty = current_date
  where id = v_uid;

  return jsonb_build_object('status','ok','streak',v_new_streak,'aura',v_balance);
end;
$$;
grant execute on function public.daily_checkin() to authenticated;

create or replace function public.sync_inactivity_penalty()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public._require_aura_member();
  v_last_checkin date;
  v_last_penalty date;
  v_anchor date;
  v_days integer;
  v_penalty integer;
  v_balance double precision;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;

  select last_checkin, last_inactivity_penalty
  into v_last_checkin, v_last_penalty
  from public.profiles
  where id = v_uid
  for update;

  if v_last_checkin is null then
    update public.profiles set last_inactivity_penalty = current_date where id = v_uid;
    return jsonb_build_object('status','none');
  end if;

  v_anchor := greatest(v_last_checkin, coalesce(v_last_penalty, v_last_checkin));
  v_days := greatest((current_date - v_anchor) - 1, 0);

  if v_days <= 0 then return jsonb_build_object('status','none'); end if;

  v_penalty := least(v_days * 2, 20);
  v_balance := public._apply_aura_delta(v_uid,-v_penalty,'inactivity','Missed ' || v_days || ' days — streak reset');

  update public.profiles
  set streak = 0,
      last_inactivity_penalty = current_date - 1
  where id = v_uid;

  return jsonb_build_object('status','penalty','penalty',v_penalty,'aura',v_balance);
end;
$$;
grant execute on function public.sync_inactivity_penalty() to authenticated;

create or replace function public.apply_daily_inactivity_penalties()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r record;
  v_anchor date;
  v_days integer;
  v_penalty integer;
  v_count integer := 0;
  v_total double precision := 0;
begin
  for r in
    select id, last_checkin, last_inactivity_penalty
    from public.profiles
    where last_checkin is not null
    order by id
  loop
    v_anchor := greatest(r.last_checkin, coalesce(r.last_inactivity_penalty, r.last_checkin));
    v_days := greatest((current_date - v_anchor) - 1, 0);
    if v_days > 0 then
      v_penalty := least(v_days * 2, 20);
      perform public._apply_aura_delta(
        r.id,
        -v_penalty,
        'inactivity',
        'Missed ' || v_days || ' days — streak reset'
      );
      update public.profiles
      set streak = 0,
          last_inactivity_penalty = current_date - 1
      where id = r.id;
      v_count := v_count + 1;
      v_total := v_total + v_penalty;
    end if;
  end loop;

  return jsonb_build_object('status','ok','users_penalized',v_count,'aura_removed',v_total);
end;
$$;
revoke all on function public.apply_daily_inactivity_penalties() from public, anon, authenticated;
grant execute on function public.apply_daily_inactivity_penalties() to service_role;

-- Friendship RPCs.
create or replace function public.send_friend_request(p_target_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public._require_aura_member();
  v_row public.friendships%rowtype;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;
  if p_target_id = v_uid then raise exception 'cannot friend yourself'; end if;

  select * into v_row
  from public.friendships
  where least(requester_id,addressee_id)=least(v_uid,p_target_id)
    and greatest(requester_id,addressee_id)=greatest(v_uid,p_target_id)
  for update;

  if found then
    if v_row.status = 'pending' and v_row.addressee_id = v_uid then
      update public.friendships set status='accepted', updated_at=now() where id=v_row.id;
      return jsonb_build_object('status','accepted','id',v_row.id);
    end if;
    return jsonb_build_object('status',v_row.status,'id',v_row.id);
  end if;

  insert into public.friendships(requester_id,addressee_id,status)
  values (v_uid,p_target_id,'pending')
  returning * into v_row;

  return jsonb_build_object('status','pending','id',v_row.id);
end;
$$;
grant execute on function public.send_friend_request(uuid) to authenticated;

create or replace function public.respond_friend_request(p_friendship_id bigint, p_accept boolean)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public._require_aura_member();
  v_status text;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;

  update public.friendships
  set status = case when p_accept then 'accepted' else 'declined' end,
      updated_at = now()
  where id = p_friendship_id
    and addressee_id = v_uid
    and status = 'pending'
  returning status into v_status;

  if v_status is null then raise exception 'request not found'; end if;
  return jsonb_build_object('status',v_status);
end;
$$;
grant execute on function public.respond_friend_request(bigint,boolean) to authenticated;

