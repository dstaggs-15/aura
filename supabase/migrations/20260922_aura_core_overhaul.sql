-- Internal helpers. Never grant these directly to app users.
create or replace function public._aura_vote_cost(v integer)
returns double precision
language sql
immutable
as $$
  select case v
    when 1 then 1
    when 5 then 2
    when 10 then 5
    when 50 then 20
    else 0
  end;
$$;

create or replace function public._apply_aura_delta(
  p_user_id uuid,
  p_delta double precision,
  p_type text,
  p_description text
)
returns double precision
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old double precision;
  v_new double precision;
  v_all_time double precision;
begin
  select aura, coalesce(aura_all_time, aura, 0)
  into v_old, v_all_time
  from public.profiles
  where id = p_user_id
  for update;

  if not found then
    raise exception 'profile not found';
  end if;

  v_new := round((coalesce(v_old, 0) + p_delta)::numeric, 1)::double precision;
  v_all_time := greatest(v_all_time, v_new);

  update public.profiles
  set aura = v_new,
      aura_all_time = v_all_time
  where id = p_user_id;

  insert into public.aura_ledger(user_id, amount, type, description, balance_after)
  values (
    p_user_id,
    round(p_delta::numeric, 1)::double precision,
    p_type,
    p_description,
    v_new
  );

  return v_new;
end;
$$;

create or replace function public._clown_tax_rate(p_aura double precision)
returns double precision
language sql
immutable
as $$
  select case
    when p_aura < -500 then 0.45
    when p_aura < -100 then 0.35
    when p_aura < 0 then 0.25
    else 0
  end;
$$;

create or replace function public._apply_income_with_clown_tax(
  p_user_id uuid,
  p_amount double precision,
  p_type text,
  p_description text
)
returns double precision
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance double precision;
  v_rate double precision;
  v_tax double precision := 0;
  v_net double precision := p_amount;
  v_bucket double precision;
begin
  select aura into v_balance
  from public.profiles
  where id = p_user_id
  for update;

  if p_amount > 0 and v_balance < 0 then
    v_rate := public._clown_tax_rate(v_balance);
    v_tax := round((p_amount * v_rate)::numeric, 1)::double precision;
    v_net := round((p_amount - v_tax)::numeric, 1)::double precision;

    select amount into v_bucket from public.tax_bucket where id = 1 for update;
    update public.tax_bucket
    set amount = round((coalesce(v_bucket, 0) + v_tax)::numeric, 1)::double precision
    where id = 1;
  end if;

  return public._apply_aura_delta(p_user_id, v_net, p_type, p_description);
end;
$$;

