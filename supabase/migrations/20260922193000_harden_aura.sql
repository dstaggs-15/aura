-- Schedule automatic penalties and Monday 00:00 UTC weekly settlement when pg_cron is available.
do $$
begin
  create extension if not exists pg_cron with schema extensions;
exception when others then
  raise notice 'pg_cron could not be enabled automatically; schedule the two functions in Supabase Cron manually.';
end $$;

do $$
begin
  if exists(select 1 from pg_extension where extname='pg_cron') then
    perform cron.unschedule(jobid) from cron.job where jobname in ('aura-daily-penalties','aura-weekly-settlement');
    perform cron.schedule('aura-daily-penalties','15 0 * * *','select public.apply_inactivity_penalties_daily();');
    perform cron.schedule('aura-weekly-settlement','0 0 * * 1','select public.settle_weekly_round();');
  end if;
exception when others then
  raise notice 'Cron scheduling skipped: %', sqlerrm;
end $$;

commit;
